#!/usr/bin/env python3
"""Write openspec/roadmap.md: one line per thing the project did, is doing or plans.

The question it answers is "is this feature already there, was this bug already fixed"
without re-reading the history. It is an index to search, not a document to read at the
start of every change: each line points at the archived change or the commit that holds
the detail.

Sources, all rewritten on every run:
  In progress        the open changes in openspec/changes/, with their task count
  Archived changes   openspec/changes/archive/<date>-<name>/
  Features, Fixes    `feat` and `fix` commits (Conventional Commits) that touch the project
The 'Planned' section is written by hand - ideas that have no change yet - and is kept.

Usage: python roadmap.py <project-root>
Writes <project-root>/openspec/roadmap.md and prints its path. Exit 3 = no openspec directory.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

COMMENT_RE = re.compile(r"<!--.*?-->", re.S)
COMMIT_RE = re.compile(r"^(feat|fix)(?:\(([^)]*)\))?(!)?:\s*(.+)$", re.I)
ARCHIVED_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-(.+)$")
CHECKBOX_RE = re.compile(r"^\s*- \[([ xX])\]", re.M)
LIST_ITEM_RE = re.compile(r"^\s*[-*]\s+")
SUMMARY_MAX = 120
NONE = "- none yet"
PLANNED_HINT = ("<!-- By hand: one line per idea that has no change yet. roadmap.py keeps this "
                "section as it is. -->")
INTRO = """# Roadmap

Generated by the lcd-spec skill (`roadmap.py`) from the open and archived changes and from
the `feat` / `fix` commits of this project. It is an index: search it when you need to know
whether a feature already exists or a bug was already fixed, then follow the line to the
change or the commit. Do not read it through. Everything except "Planned" is rewritten on
every run."""


def _read(path: Path) -> str:
    try:
        # utf-8-sig: a BOM in front of a first-line '## Why' would hide the heading
        return path.read_bytes().decode("utf-8-sig", errors="replace").replace("\r\n", "\n")
    except OSError:
        return ""


def _section(text: str, title: str) -> str:
    m = re.search(rf"^##\s+{re.escape(title)}[^\n]*\n", text, re.M | re.I)
    if not m:
        return ""
    rest = text[m.end():]
    nxt = re.search(r"^##\s", rest, re.M)
    return rest[: nxt.start()] if nxt else rest


# --- commits ---------------------------------------------------------------------

def commits(project: Path) -> dict:
    """{'feat': [line, ...], 'fix': [...]}, newest first. No repository, no lines."""
    try:
        # '-- .' keeps a repository that merely contains the project out of its roadmap
        log = subprocess.run(
            ["git", "-C", str(project), "log", "--date=short", "--pretty=format:%h%x09%ad%x09%s", "--", "."],
            check=True, capture_output=True).stdout.decode("utf-8", errors="replace")
    except (OSError, subprocess.CalledProcessError):
        log = ""
    out = {"feat": [], "fix": []}
    for row in log.splitlines():
        sha, date, subject = (row.split("\t", 2) + ["", ""])[:3]
        m = COMMIT_RE.match(subject)
        if m:
            kind, scope, breaking, text = m.groups()
            out[kind.lower()].append(f"- {date} {scope + ': ' if scope else ''}{text.strip()}"
                                     f"{' (BREAKING)' if breaking else ''} ({sha})")
    return out


# --- changes ---------------------------------------------------------------------

def _summary(change: Path) -> str:
    """What the change does, in one line: the first 'What Changes' item, else its 'Why'."""
    proposal = COMMENT_RE.sub("", _read(change / "proposal.md"))
    lines = [line for line in _section(proposal, "What Changes").splitlines() if LIST_ITEM_RE.match(line)]
    lines += [line for line in _section(proposal, "Why").splitlines() if line.strip()]
    if not lines:
        return ""
    text = LIST_ITEM_RE.sub("", lines[0], count=1).replace("*", "").strip()
    return text if len(text) <= SUMMARY_MAX else text[: SUMMARY_MAX - 3].rstrip() + "..."


def _described(change: Path, name: str) -> str:
    specs = change / "specs"
    capabilities = sorted(p.name for p in specs.iterdir() if p.is_dir()) if specs.is_dir() else []
    summary = _summary(change)
    return (name + (f" [{', '.join(capabilities)}]" if capabilities else "")
            + (f" - {summary}" if summary else ""))


def _directories(path: Path) -> list:
    return sorted(p for p in path.iterdir() if p.is_dir()) if path.is_dir() else []


def archived(openspec: Path) -> list:
    """One line per archived change, newest first."""
    out = []
    for change in reversed(_directories(openspec / "changes" / "archive")):
        m = ARCHIVED_RE.match(change.name)
        if m:
            out.append(f"- {m.group(1)} {_described(change, m.group(2))} "
                       f"→ changes/archive/{change.name}/")
    return out


def in_progress(openspec: Path) -> list:
    """One line per open change, with how many of its tasks are ticked."""
    out = []
    for change in _directories(openspec / "changes"):
        if change.name == "archive":
            continue
        boxes = CHECKBOX_RE.findall(COMMENT_RE.sub("", _read(change / "tasks.md")))
        done = sum(box != " " for box in boxes)
        progress = f"{done}/{len(boxes)} tasks" if boxes else "no plan yet"
        out.append(f"- {_described(change, change.name)} ({progress})")
    return out


# --- the file --------------------------------------------------------------------

def build(project: Path) -> str:
    openspec = Path(project) / "openspec"
    planned = _section(_read(openspec / "roadmap.md"), "Planned").strip() or PLANNED_HINT
    history = commits(Path(project))
    parts = [INTRO, "## Planned\n\n" + planned]
    for title, lines in (("In progress", in_progress(openspec)), ("Archived changes", archived(openspec)),
                         ("Features", history["feat"]), ("Fixes", history["fix"])):
        parts.append(f"## {title}\n\n" + "\n".join(lines or [NONE]))
    return "\n\n".join(parts) + "\n"


def write(project: Path) -> Path:
    openspec = Path(project) / "openspec"
    if not openspec.is_dir():
        raise FileNotFoundError(f"{openspec} not found - run `openspec init` in {project} first")
    path = openspec / "roadmap.md"
    path.write_bytes(build(project).encode("utf-8"))
    return path


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        path = write(Path(argv[0]))
    except OSError as exc:
        print(exc, file=sys.stderr)
        return 3
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
